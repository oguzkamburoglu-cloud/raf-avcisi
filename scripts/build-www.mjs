// Builds www/ from src/: copies the game and bundles only the font files it needs.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const src = path.join(root, "src");
const www = path.join(root, "www");
const fontsOut = path.join(www, "fonts");
fs.rmSync(www, { recursive: true, force: true });
fs.mkdirSync(fontsOut, { recursive: true });

for (const f of fs.readdirSync(src)) fs.copyFileSync(path.join(src, f), path.join(www, f));

const html = fs.readFileSync(path.join(src, "index.html"), "utf8");
const used = new Set([...html].map((c) => c.codePointAt(0)).filter((c) => c > 0x2000));

function inRange(range) {
  return range.split(",").some((part) => {
    const [a, b] = part.trim().replace(/^U\+/i, "").split("-").map((x) => parseInt(x, 16));
    for (const c of used) if (c >= a && c <= (b ?? a)) return true;
    return false;
  });
}

const pick = [
  // [package, css file, keep(block) ]
  ["roboto", "latin-400.css"], ["roboto", "latin-ext-400.css"],
  ["roboto", "latin-500.css"], ["roboto", "latin-ext-500.css"],
  ["roboto", "latin-700.css"], ["roboto", "latin-ext-700.css"],
  // Cyrillic for the Russian translation
  ["roboto", "cyrillic-400.css"], ["roboto", "cyrillic-500.css"], ["roboto", "cyrillic-700.css"],
  // variable Fraunces with the optical-size axis, same as the web version (opsz 9..144)
  ["../@fontsource-variable/fraunces", "opsz.css"],
  ["noto-color-emoji", "400.css", true]
];

let css = "/* Generated by scripts/build-www.mjs - bundled fonts (SIL Open Font License) */\n";
let bytes = 0;
for (const [pkg, file, filter] of pick) {
  const dir = path.join(root, "node_modules/@fontsource", pkg);
  const text = fs.readFileSync(path.join(dir, file), "utf8");
  for (const block of text.match(/@font-face\s*{[^}]*}/g) || []) {
    const range = (block.match(/unicode-range:\s*([^;]+);/) || [])[1];
    if (filter && range && !inRange(range)) continue;
    const woff2 = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
    if (/vietnamese|greek/.test(woff2)) continue;
    fs.copyFileSync(path.join(dir, "files", woff2), path.join(fontsOut, woff2));
    bytes += fs.statSync(path.join(fontsOut, woff2)).size;
    css += block
      .replace(/src:[^;]+;/, `src: url(./${woff2}) format('woff2');`)
      .replace(/font-display:\s*swap/, "font-display: block")
      .replace("'Fraunces Variable'", "'Fraunces'")
      // The bundled emoji font is OpenType-SVG: iOS (WebKit) draws it, Android WebView (Chromium) does not.
      // Android already ships Noto Color Emoji as its system emoji, so the game only uses this font on iOS.
      .replace("'Noto Color Emoji'", "'Raf Emoji'") + "\n";
  }
}
fs.writeFileSync(path.join(fontsOut, "fonts.css"), css);
console.log(`www/ hazır. Fontlar: ${(bytes / 1024 / 1024).toFixed(1)} MB`);
